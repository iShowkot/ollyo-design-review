#!/usr/bin/env bash
# Concatenates the skill into one Markdown file for tools that only accept a
# single pasted prompt or uploaded file (Grok, ChatGPT, Gemini Gems, etc.).
# Usage: ./scripts/bundle.sh            -> all products
#        ./scripts/bundle.sh tutor-lms  -> only that product (smaller prompt)
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p dist
out="dist/ollyo-design-review${1:+-$1}.md"

if [ -n "${1:-}" ]; then
  products=("products/$1.md")
  [ -f "${products[0]}" ] || { echo "No such product: $1" >&2; exit 1; }
else
  products=()
  for f in products/*.md; do
    [ "$(basename "$f")" = "_template.md" ] || products+=("$f")
  done
fi

{
  echo "<!-- Generated by scripts/bundle.sh — do not edit; edit the source files instead. -->"
  for f in SKILL.md rubrics/communication.md rubrics/aesthetics.md rubrics/hard-fails.md templates/review-output.md "${products[@]}"; do
    printf '\n\n---\n<!-- FILE: %s -->\n\n' "$f"
    cat "$f"
  done
} > "$out"
echo "Wrote $out"
